/// Feed one record at a time, each with a new parser that only knows the user rows found so
/// far (what the indexer hands an appending parser).
fn feed_line_by_line(path: &std::path::Path) -> Vec<agent_session_core::model::MessageRow> {
    let bytes = std::fs::read(path).unwrap();
    let mut rows: Vec<agent_session_core::model::MessageRow> = Vec::new();
    let mut offset = 0;
    for line in bytes.split_inclusive(|b| *b == b'\n') {
        let seen = rows.iter().filter(|m| m.role == Role::User).map(|m| m.uuid.clone()).collect();
        let fed = TranscriptParser::new("s").seen_user_uuids(seen).feed(line, offset);
        offset += fed.consumed;
        rows.extend(fed.messages);
    }
    rows
}

