#[test]
fn delta_applied_on_top_of_an_existing_session_only_adds() {
    // A second feed of a new prompt + reply on top of a summary from the first parse.
    let sb = sandbox();
    let path = sb.transcript(ALPHA, S2);
    let full = parse_transcript(&path).unwrap();
    let mut summary = full.summary.clone();
    let extra = concat!(
        r#"{"parentUuid":"x","isSidechain":false,"type":"user","message":{"role":"user","content":"And now in French"},"uuid":"u-new","timestamp":"2026-09-06T00:00:00.000Z","sessionId":"22222222-aaaa-4bbb-8ccc-000000000002","cwd":"/Users/me/Code/alpha","gitBranch":"main","entrypoint":"sdk-cli","version":"2.1.261"}"#, "\n",
        r#"{"parentUuid":"u-new","isSidechain":false,"message":{"model":"claude-haiku-4-5-20251001","id":"m","type":"message","role":"assistant","content":[{"type":"text","text":"Bonjour mon ami."}],"usage":{"input_tokens":1,"output_tokens":2}},"type":"assistant","uuid":"a-new","timestamp":"2026-09-06T00:00:01.000Z","sessionId":"22222222-aaaa-4bbb-8ccc-000000000002","cwd":"/Users/me/Code/alpha","gitBranch":"main","version":"2.1.261"}"#, "\n",
    );
    let mut parser = TranscriptParser::new(S2);
    let fed = parser.feed(extra.as_bytes(), full.consumed);
    assert_eq!(fed.messages.len(), 2);
    assert_eq!(fed.messages[0].byte_offset, full.consumed);
    parser.delta().apply(&mut summary);
    assert_eq!(summary.user_msg_count, 2);
    assert_eq!(summary.assistant_msg_count, 2);
    assert_eq!(summary.first_prompt, "Say hello in exactly three words.", "first prompt is never replaced");
    assert_eq!(summary.started_at, full.summary.started_at);
    assert_eq!(summary.last_prompt.as_deref(), Some("And now in French"));
    assert_eq!(summary.last_message.as_deref(), Some("Bonjour mon ami."));
    assert_eq!(summary.cc_version.as_deref(), Some("2.1.261"));
}

#[test]
fn unknown_record_types_and_broken_lines_are_ignored() {
    let text = concat!(
        r#"{"type":"brand-new-thing","payload":{"deep":[1,2,3]},"sessionId":"s"}"#, "\n",
        "garbage line\n",
        "\n",
        r#"{"type":"user","message":{"role":"user","content":"hi"},"uuid":"u1","timestamp":"2026-01-01T00:00:00.000Z","sessionId":"s"}"#, "\n",
    );
    let mut parser = TranscriptParser::new("s");
    let fed = parser.feed(text.as_bytes(), 0);
    assert_eq!(fed.messages.len(), 1);
    assert_eq!(fed.consumed, text.len() as u64);
    let mut s = agent_session_core::model::SessionSummary::transcript("s", "p", std::path::Path::new("/dev/null"));
    parser.delta().apply(&mut s);
    assert_eq!(s.first_prompt, "hi");
    assert_eq!(s.user_msg_count, 1);
}
