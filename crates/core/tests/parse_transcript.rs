//! Behavior: parsing one transcript yields the same session facts as the Python reference
//! (`session_info`) plus the derived fields the table needs. Fixture: tests/fixtures/claude.

mod common;

use agent_session_core::claude::parse::{TranscriptParser, parse_transcript};
use agent_session_core::model::{Role, Source};
use common::*;

fn ts(iso: &str) -> i64 {
    chrono::DateTime::parse_from_rfc3339(iso).unwrap().timestamp_millis()
}

#[test]
fn rich_session_summary_matches_reference_semantics() {
    let sb = sandbox();
    let path = sb.transcript(ALPHA, S1);
    let parsed = parse_transcript(&path).unwrap();
    let s = &parsed.summary;

    assert_eq!(s.id, S1);
    assert_eq!(s.source, Source::Transcript);
    assert_eq!(s.project_key, ALPHA);
    assert_eq!(s.cwd.as_deref(), Some("/Users/me/Code/alpha"));
    assert_eq!(s.file_path.as_deref(), Some(path.as_path()));
    assert_eq!(s.file_size, Some(std::fs::metadata(&path).unwrap().len()));
    assert_eq!(s.updated_at, MTIME_S1, "updated = file mtime for transcripts");

    // first prompt: the /init command (the isMeta caveat before it does not count)
    assert_eq!(s.first_prompt, "/init --force");
    assert_eq!(s.started_at, Some(ts("2026-09-01T08:00:01.000Z")));
    // prompts: /init, "Please refactor…", "What is in this screenshot?" (image carrier + sidechain + tool results excluded)
    assert_eq!(s.user_msg_count, 3);
    assert_eq!(s.assistant_msg_count, 4, "assistant records that carry a text block");
    assert_eq!(s.last_prompt.as_deref(), Some("What is in this screenshot?"));
    assert_eq!(s.last_message.as_deref(), Some("Done. The parser now handles nested arrays; 14 tests pass."));

    assert_eq!(s.title.as_deref(), Some("Parser refactor"), "custom-title beats ai-title");
    assert_eq!(s.tool_use_count, 3);
    assert_eq!(s.tool_counts.get("Bash"), Some(&2));
    assert_eq!(s.tool_counts.get("Read"), Some(&1));
    assert_eq!(s.git_branch.as_deref(), Some("feat/parser"), "last seen branch");
    assert_eq!(s.cc_version.as_deref(), Some("2.1.260"));
    assert_eq!(s.entrypoint.as_deref(), Some("cli"));
    assert_eq!(s.permission_mode.as_deref(), Some("bypassPermissions"), "last permission-mode record");
    assert!(!s.is_background);
    assert_eq!(s.total_cost_usd, Some(1.2345));
    assert_eq!(s.duration_ms, Some(3_600_000));
    assert_eq!(s.lines_added, Some(12));
    assert_eq!(s.lines_removed, Some(3));
    assert_eq!(s.pr_url.as_deref(), Some("https://github.com/me/alpha/pull/7"));
    assert_eq!(s.files_touched.iter().collect::<Vec<_>>(), vec!["/Users/me/Code/alpha/src/parse.rs"]);
    assert_eq!(s.models.iter().collect::<Vec<_>>(), vec!["claude-opus-5"]);
}

#[test]
fn rich_session_messages_keep_only_user_and_assistant_text() {
    let sb = sandbox();
    let parsed = parse_transcript(&sb.transcript(ALPHA, S1)).unwrap();
    let texts: Vec<(Role, &str, bool)> =
        parsed.messages.iter().map(|m| (m.role, m.text.as_str(), m.is_meta)).collect();
    assert_eq!(
        texts,
        vec![
            (Role::User, "<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>", true),
            (Role::User, "<command-message>init is running…</command-message>\n<command-name>/init</command-name>\n<command-args>--force</command-args>", false),
            (Role::Assistant, "I'll set things up.", false),
            (Role::Assistant, "Here is the plan: refactor the parser.", false),
            (Role::User, "<system-reminder>\nremember to be nice\n</system-reminder>\nPlease refactor the parser to handle nested arrays", false),
            (Role::User, "[Image: source: clipboard]", false),
            (Role::User, "What is in this screenshot?", false),
            (Role::Assistant, "It shows a terminal running cargo test.", false),
            (Role::User, "Explore the repo and report back", false),
            (Role::Assistant, "Done. The parser now handles nested arrays; 14 tests pass.", false),
        ]
    );
    // every message points back at its own line in the file
    let bytes = std::fs::read(sb.transcript(ALPHA, S1)).unwrap();
    for m in &parsed.messages {
        let line = &bytes[m.byte_offset as usize..(m.byte_offset + m.byte_len) as usize];
        assert!(line.starts_with(b"{") && line.ends_with(b"}"), "offset/len select one JSON line");
        assert!(!line.contains(&b'\n'));
        assert!(!m.uuid.is_empty());
        assert!(m.ts > 0);
    }
    let last = parsed.messages.last().unwrap();
    assert_eq!(last.model.as_deref(), Some("claude-opus-5"));
    assert_eq!((last.input_tokens, last.output_tokens), (Some(5), Some(50)));
    assert_eq!(parsed.consumed, bytes.len() as u64, "a complete file is consumed to the end");
}

