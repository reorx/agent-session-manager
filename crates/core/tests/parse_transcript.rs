fn kinds_of(lines: &[serde_json::Value]) -> Vec<(TextKind, String)> {
    let text: String = lines.iter().map(|l| format!("{l}\n")).collect();
    TranscriptParser::new("s").feed(text.as_bytes(), 0).messages.into_iter().map(|m| (m.kind, m.text)).collect()
}

fn user_rec(uuid: &str, content: serde_json::Value, extra: serde_json::Value) -> serde_json::Value {
    let mut rec = serde_json::json!({"type": "user", "uuid": uuid, "timestamp": "2026-01-01T00:00:00.000Z", "message": {"role": "user", "content": content}});
    rec.as_object_mut().unwrap().extend(extra.as_object().unwrap().clone());
    rec
}

